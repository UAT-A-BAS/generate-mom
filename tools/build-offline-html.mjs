import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const artifactPath = resolve(projectRoot, "generate-mom-offline.html");

function replaceOnce(source, pattern, replacement, label) {
  const matches = [...source.matchAll(new RegExp(pattern.source, "g"))];
  if (matches.length !== 1) {
    throw new Error(`Expected exactly one ${label}; found ${matches.length}.`);
  }
  return source.replace(pattern, () => replacement);
}

export function buildOfflineHtml() {
  const source = readFileSync(resolve(projectRoot, "index.html"), "utf8");
  const macro = readFileSync(resolve(projectRoot, "ExportMOMToDraft.bas"));
  const sha256 = (value) => createHash("sha256").update(value).digest("hex");
  const marker = [
    '<meta name="mom-offline-artifact" content="1">',
    `<!-- MOM Generator offline artifact; generated by tools/build-offline-html.mjs.`,
    `     index.html SHA-256: ${sha256(source)}`,
    `     ExportMOMToDraft.bas SHA-256: ${sha256(macro)} -->`,
    '<meta http-equiv="Content-Security-Policy" content="connect-src \'none\'; object-src \'none\';">',
    "<script>window.__MOM_OFFLINE__ = true;</script>",
  ].join("\n    ");

  const documentHead = /^<!DOCTYPE html>\s*<html lang="id">\s*<head>/;
  const headPrefix = source.match(documentHead)?.[0] || "";
  let html = replaceOnce(source, documentHead, `${headPrefix}\n    ${marker}`, "document head");
  html = replaceOnce(
    html,
    /href="\.\/ExportMOMToDraft\.bas"/,
    `href="data:application/octet-stream;base64,${macro.toString("base64")}"`,
    "Outlook macro link"
  );
  // The runtime guard already disables collaboration. The published offline file must
  // also contain no collaboration endpoint literal at all, so the single endpoint
  // builder is replaced with an inert stub.
  html = replaceOnce(
    html,
    /function buildCollabApiUrl\(sessionId\) \{[\s\S]*?\n      \}/,
    'function buildCollabApiUrl(sessionId) {\n        throw new Error("Collaboration is disabled in the offline artifact.");\n      }',
    "collaboration endpoint builder"
  );

  if (/workers\.dev|pages\.dev|wss?:\/\/|\/api\/collab/i.test(html)) {
    throw new Error("Offline artifact still contains a collaboration endpoint.");
  }
  if (/<script\b[^>]*\bsrc\s*=|<link\b[^>]*\bhref\s*=\s*["']https?:/i.test(html)) {
    throw new Error("Offline artifact references an external script or stylesheet.");
  }
  return { html, sourceBytes: Buffer.byteLength(source), artifactBytes: Buffer.byteLength(html) };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    if (args.some((arg) => arg !== "--check") || args.length > 1) {
      throw new Error("Usage: node tools/build-offline-html.mjs [--check]");
    }
    const { html, sourceBytes, artifactBytes } = buildOfflineHtml();
    if (args.includes("--check")) {
      let committed;
      try { committed = readFileSync(artifactPath, "utf8"); } catch (error) {
        if (error.code !== "ENOENT") throw error;
      }
      if (committed !== html) {
        throw new Error("Offline artifact is missing or stale. Run node tools/build-offline-html.mjs and commit the result.");
      }
    } else {
      writeFileSync(artifactPath, html);
    }
    console.log(`${args.includes("--check") ? "PASS fresh" : "Built"} generate-mom-offline.html: ${artifactBytes} bytes; injected ${artifactBytes - sourceBytes} net bytes.`);
  } catch (error) {
    console.error(`FAIL: ${error.message}`);
    process.exitCode = 1;
  }
}
